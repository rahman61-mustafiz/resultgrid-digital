function answerIn(answer: string, field: string | undefined, values: string[]): Condition {
  return field === undefined ? { answer, in: values } : { answer, field, in: values }
}

function inScope(...items: string[]): Condition {
  return answerIn("E13.Q02", "scope", items)
}

